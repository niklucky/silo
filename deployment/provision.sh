#!/usr/bin/env bash
# Workstation entry point. Only provision-host.sh runs as root on the VPS.
set -euo pipefail
HERE=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
ROOT=$(cd "$HERE/.." && pwd)
# shellcheck source=deployment/config.sh
. "$HERE/config.sh"

MODE=full
SKIP_CERTS=0
ENV_FILE="$HERE/.env.production"
for arg in "$@"; do
  case "$arg" in
    --check|--nginx-only|--backups-only)
      [ "$MODE" = full ] || die 'Choose one mode'
      MODE=${arg#--}; MODE=${MODE%-only} ;;
    --skip-certs) SKIP_CERTS=1 ;;
    --env-file=*) ENV_FILE=${arg#*=} ;;
    -h|--help)
      printf '%s\n' 'Usage: deployment/provision.sh [--check|--nginx-only|--backups-only] [--skip-certs] [--env-file=PATH]' \
        '  --check: read-only VPS preflight; no key or DNS readiness required' \
        '  --skip-certs: full provision with HTTP 503 until certificates are issued'
      exit 0 ;;
    *) die "Unknown option: $arg" ;;
  esac
done
[ "$MODE" = full ] || [ "$SKIP_CERTS" = 0 ] || die '--skip-certs requires a full provision'
load_config "$ENV_FILE"

ssh_opts=(-o BatchMode=yes -o ConnectTimeout=15 -o StrictHostKeyChecking=yes -p "$SSH_PORT")
target="$PROVISION_USER@$SSH_HOST"
# Values in remote command strings below are validated or generated by mktemp.
# shellcheck disable=SC2029
remote() { ssh "${ssh_opts[@]}" "$target" "$@"; }

if [ "$MODE" = check ]; then
  remote "bash -s -- '$SERVER_PORT' '$SILO_UID' '$SILO_GID'" <<'CHECK'
set -euo pipefail
. /etc/os-release
[ "$ID" = debian ] && [ "$VERSION_ID" = 13 ] || { echo 'Expected Debian 13' >&2; exit 1; }
[ "$(id -u)" = 0 ] || { echo 'Provision as root' >&2; exit 1; }
uname -m
docker info --format '{{json .Plugins.Log}}'
docker compose version
nginx -t
systemctl is-active docker nginx
printf '\nRequested port and account IDs (empty means free):\n'
ss -ltnH "sport = :$1"
getent passwd "$2" || true
getent group "$3" || true
printf '\nExisting nginx sites (will be retained):\n'
ls -l /etc/nginx/sites-enabled
CHECK
  exit 0
fi

key="$DEPLOY_PUBLIC_KEY_PATH"
case "$key" in /*) ;; *) key="$ROOT/$key" ;; esac
if [ "$MODE" = full ]; then
  [ -s "$key" ] || die "Missing $key; generate the deployment key first (see README)"
  read -r first_line < "$key"
  case "$first_line" in ssh-*|ecdsa-*|sk-*) ;; *) die 'DEPLOY_PUBLIC_KEY_PATH must contain a public key' ;; esac
  [ "$(wc -l < "$key" | tr -d ' ')" = 1 ] || die 'Expected exactly one public key line'
  ssh-keygen -lf "$key" >/dev/null || die 'Invalid public key'
fi

bundle=$(mktemp -d)
stage=''
cleanup() {
  local rc=$?
  trap - EXIT
  if [ -n "$stage" ]; then
    if [ "$rc" = 0 ]; then
      remote "find '$stage' -depth -delete" >/dev/null 2>&1 || true
    else
      printf 'Failed provision: retained remote staging/rollback files at %s\n' "$stage" >&2
    fi
  fi
  find "$bundle" -depth -delete
  exit "$rc"
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
umask 077
cp "$HERE/provision-host.sh" "$HERE/backup.sh" "$bundle/"
cp -R "$HERE/nginx" "$bundle/"
[ "$MODE" != full ] || cp "$key" "$bundle/deploy.pub"
for name in MODE SKIP_CERTS DOMAIN CERT_EMAIL SILO_UID SILO_GID SERVER_PORT BACKUP_KEEP_DAYS; do
  printf '%s=%q\n' "$name" "${!name}" >> "$bundle/settings.sh"
done
stage=$(remote 'umask 077; mktemp -d /tmp/silo-provision.XXXXXXXX')
case "$stage" in /tmp/silo-provision.*) ;; *) stage=''; die 'Unexpected staging directory' ;; esac
tar_opts=()
[ "$(uname)" != Darwin ] || tar_opts+=(--no-mac-metadata --no-xattrs)
# bash 3.2 needs the conditional expansion for an empty array under nounset.
COPYFILE_DISABLE=1 tar ${tar_opts[@]+"${tar_opts[@]}"} -C "$bundle" -cf - . | remote "tar -C '$stage' -xf -"
remote "bash '$stage/provision-host.sh' '$stage'"
